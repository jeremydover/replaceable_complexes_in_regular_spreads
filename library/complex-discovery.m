/*
  Complex discovery / complex-model generation helper.

  Intended workflow:

      q := 5;
      load "library/complex-discovery.m";
      load "implementations/myComplexConstruction.m";

      complexes := [... constructed lambda-s complexes ...];
      instances := [
          Sprintf("{\"q\":%o,\"parameter\":%o}", q, a),
          ...
      ];

      IdentifyComplexModels(complexes, "myComplexConstruction", instances);

  Here a constructed lambda-s complex is simply a sequence/set of lambda-s
  circles.  If the construction already returns literal CSet circles, use
  IdentifyCSetComplex / IdentifyAndWriteCSetComplexModel instead.

  Requires:
      library/web-discovery.m
      library/complex-catalog.m

  complex-catalog.m is generated by tools/build_complex_catalog.py from
  complexes.jsonl.
*/

load "library/web-discovery.m";
load "library/complex-catalog.m";


/* Convert a construction's lambda-s circle list into a literal subset of CSet. */
ComplexToCSet := function(lambdaSComplex)
    result := {};
    for ls in lambdaSComplex do
        lambda := F!ls[1];
        s := F!ls[2];
        circle := { Position(P, V![1, lambda + s*x]) : x in F | x^(q+1) eq 1 };
        if not circle in circles then
            error "Constructed complex contains something that is not a circle in CSet";
        end if;
        Include(~result, circle);
    end for;
    if #result ne #lambdaSComplex then
        error "Duplicate circles occurred while converting constructed complex";
    end if;
    return result;
end function;


/* The connected-component decomposition used by step4.m. */
ComplexConnectedComponents := function(complex)
    if #complex eq 0 then
        error "Cannot identify an empty complex";
    end if;

    covered := &join complex;
    components := [];

    while #covered gt 0 do
        thisComp := {};
        p := Rep(covered);
        pencil := { x : x in complex | p in x };

        if #pencil eq 1 then
            thisComp := pencil;
        else
            nest := pencil;
            covered1 := (&join nest) diff (&meet nest);

            while #covered1 gt 0 do
                p := Rep(covered1);
                thisPencil := { x : x in complex | p in x and x notin nest };
                for y in thisPencil do
                    covered1 := covered1 sdiff y;
                    Include(~nest, y);
                end for;
            end while;

            thisComp := nest;
        end if;

        covered diff:= &join thisComp;
        Append(~components, thisComp);
    end while;

    return components;
end function;


/* Identify every connected component against the web catalog. */
ComplexComponentWebIDs := function(complex)
    components := ComplexConnectedComponents(complex);
    ids := [];

    for component in components do
        flag, webID, g, candidateCount := IdentifyCSetWeb(component);
        if not flag then
            error Sprintf("Could not identify a complex component after %o web candidates", candidateCount);
        end if;
        Append(~ids, webID);
    end for;

    Sort(~ids);
    return ids;
end function;


/* Cheap invariant signature used only to shortlist catalog representatives. */
ComplexInvariantSignature := function(complex)
    components := ComplexConnectedComponents(complex);
    componentSizes := [ #c : c in components ];
    Sort(~componentSizes);
    componentWebIDs := ComplexComponentWebIDs(complex);

    return <#complex, #components, componentWebIDs, componentSizes>;
end function;


complexDiscoverySameSignature := function(entry, sig)
    return entry`q eq q and
           entry`circleCount eq sig[1] and
           entry`componentCount eq sig[2] and
           entry`componentWebIDs eq sig[3] and
           entry`componentCircleCounts eq sig[4];
end function;


/* Reconstruct one catalog representative as a literal subset of CSet. */
complexDiscoveryCatalogComplex := function(entry)
    result := {};

    for serializedComponent in entry`serializedComponents do
        for seq in serializedComponent do
            Include(~result, webDiscoverySerializedCircle(seq));
        end for;
    end for;

    if #result ne entry`circleCount then
        error Sprintf("Catalog complex %o contains duplicate serialized circles", entry`id);
    end if;

    return result;
end function;


/*
  Identify one literal CSet complex. Returns:

      true, complexID, conjugatingElement, candidateCount

  or

      false, "", Identity(G), candidateCount
*/
IdentifyCSetComplex := function(complex)
    sig := ComplexInvariantSignature(complex);
    candidates := [ entry : entry in complexCatalog |
                    complexDiscoverySameSignature(entry, sig) ];

    for entry in candidates do
        refComplex := complexDiscoveryCatalogComplex(entry);
        flag, g := IsConjugate(G, CSet, complex, refComplex);
        if flag then
            return true, entry`id, g, #candidates;
        end if;
    end for;

    return false, "", G!1, #candidates;
end function;


/* Convenience wrapper for a construction's lambda-s output. */
IdentifyComplex := function(lambdaSComplex)
    return IdentifyCSetComplex(ComplexToCSet(lambdaSComplex));
end function;


/* Reuse the JSON escaping/validation routines loaded by web-discovery.m. */
WriteComplexModel := procedure(complexID, sourceID, instanceJSON, fileName : append := true)
    webDiscoveryValidateInstanceJSON(instanceJSON);
    mode := append select "a" else "w";
    fh := Open(fileName, mode);
    fprintf fh, "{\"complex\":\"%o\",\"source\":\"%o\",\"instance\":%o}\n",
        webDiscoveryEscapeJSONString(complexID),
        webDiscoveryEscapeJSONString(sourceID),
        instanceJSON;
    delete fh;
end procedure;


/* Identify one lambda-s construction result and append its model row. */
IdentifyAndWriteComplexModel := procedure(lambdaSComplex, sourceID, instanceJSON :
                                         outputFile := "complex-models.generated.jsonl",
                                         append := true,
                                         verbose := true)
    flag, complexID, g, candidateCount := IdentifyComplex(lambdaSComplex);

    if not flag then
        error Sprintf("No catalog complex matched source %o instance %o after %o candidates",
                      sourceID, instanceJSON, candidateCount);
    end if;

    WriteComplexModel(complexID, sourceID, instanceJSON, outputFile : append := append);

    if verbose then
        printf "MATCH %o  source=%o  candidates=%o\n", complexID, sourceID, candidateCount;
    end if;
end procedure;


/* Same thing when the construction already produced literal CSet circles. */
IdentifyAndWriteCSetComplexModel := procedure(complex, sourceID, instanceJSON :
                                             outputFile := "complex-models.generated.jsonl",
                                             append := true,
                                             verbose := true)
    flag, complexID, g, candidateCount := IdentifyCSetComplex(complex);

    if not flag then
        error Sprintf("No catalog complex matched source %o instance %o after %o candidates",
                      sourceID, instanceJSON, candidateCount);
    end if;

    WriteComplexModel(complexID, sourceID, instanceJSON, outputFile : append := append);

    if verbose then
        printf "MATCH %o  source=%o  candidates=%o\n", complexID, sourceID, candidateCount;
    end if;
end procedure;


/* Batch form for lambda-s construction results. */
IdentifyComplexModels := procedure(constructedComplexes, sourceID, instanceJSONs :
                                   outputFile := "complex-models.generated.jsonl",
                                   append := false,
                                   verbose := true)
    if #constructedComplexes ne #instanceJSONs then
        error "constructedComplexes and instanceJSONs must have the same length";
    end if;

    first := true;
    for i in [1..#constructedComplexes] do
        thisAppend := append or not first;
        IdentifyAndWriteComplexModel(constructedComplexes[i], sourceID, instanceJSONs[i] :
                                     outputFile := outputFile,
                                     append := thisAppend,
                                     verbose := verbose);
        first := false;
    end for;
end procedure;


/* Batch form for literal CSet complexes. */
IdentifyCSetComplexModels := procedure(constructedComplexes, sourceID, instanceJSONs :
                                      outputFile := "complex-models.generated.jsonl",
                                      append := false,
                                      verbose := true)
    if #constructedComplexes ne #instanceJSONs then
        error "constructedComplexes and instanceJSONs must have the same length";
    end if;

    first := true;
    for i in [1..#constructedComplexes] do
        thisAppend := append or not first;
        IdentifyAndWriteCSetComplexModel(constructedComplexes[i], sourceID, instanceJSONs[i] :
                                         outputFile := outputFile,
                                         append := thisAppend,
                                         verbose := verbose);
        first := false;
    end for;
end procedure;
